"""Bake templates, static files, and data/db.json into runtime_files.py.

Cloudflare Python Workers do not always mount the project folder, so the
running app reads this copy. Regenerate after changing those files:

    .\\.venv\\Scripts\\python.exe build_bundle.py
"""

import base64
import json
import zlib
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def collect():
    files = {}
    for folder in ("templates", "static", "data"):
        for path in (ROOT / folder).rglob("*"):
            if not path.is_file() or path.suffix == ".tmp":
                continue
            files[path.relative_to(ROOT).as_posix()] = path.read_text(encoding="utf-8")
    return files


def main():
    blob = base64.b64encode(
        zlib.compress(json.dumps(collect(), ensure_ascii=False).encode("utf-8"), 9)
    ).decode("ascii")
    wrapped = "\n".join(blob[i : i + 100] for i in range(0, len(blob), 100))
    target = ROOT / "runtime_files.py"
    target.write_text(
        '"""Baked site files for the Cloudflare Worker. Generated by build_bundle.py."""\n'
        "import base64\n"
        "import json\n"
        "import zlib\n"
        "\n"
        '_BLOB = """\n'
        f"{wrapped}\n"
        '"""\n'
        "\n"
        "_cache = None\n"
        "\n"
        "\n"
        "def load():\n"
        "    global _cache\n"
        "    if _cache is None:\n"
        '        raw = zlib.decompress(base64.b64decode("".join(_BLOB.split())))\n'
        "        _cache = json.loads(raw)\n"
        "    return _cache\n",
        encoding="utf-8",
    )
    print(f"{target.name} {target.stat().st_size} bytes, {len(collect())} files")


if __name__ == "__main__":
    main()
